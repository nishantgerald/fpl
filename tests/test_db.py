"""The storage seam: same SQL, two backends.

Heroku's filesystem is ephemeral, so a SQLite file in production is destroyed
several times a day and takes every account with it. This module is what lets
`accounts.py` keep its thirty-nine queries unchanged while running on Postgres.

The translation tests below need no database and are where the silent-corruption
bugs live. The integration tests need a real Postgres and skip without one:

    TEST_DATABASE_URL='postgresql://.../fpl_test' pytest tests/test_db.py

Deliberately *not* `DATABASE_URL`. These tests drop every table on teardown, so
pointing them at the variable production also reads would destroy the live
database — which is exactly what happened once, and why the fixture below now
refuses to run against it.
"""

import os
import re
import time

import pytest

from engine import accounts, db


# ------------------------------------------------------------ translation


class TestPlaceholders:
    def test_question_marks_become_percent_s(self):
        assert (
            db._to_pg_placeholders("SELECT * FROM users WHERE id = ? AND email = ?")
            == "SELECT * FROM users WHERE id = %s AND email = %s"
        )

    def test_a_question_mark_inside_a_literal_is_left_alone(self):
        """A blunt str.replace corrupts any literal containing one — and the
        stray %s it leaves behind is then read by psycopg as a placeholder,
        so the query fails with a confusing arity error rather than obviously."""
        sql = "SELECT ? WHERE note = 'really?'"

        assert db._to_pg_placeholders(sql) == "SELECT %s WHERE note = 'really?'"

    def test_a_question_mark_in_a_comment_is_left_alone(self):
        sql = "SELECT ?\n-- is this right?\nFROM users"

        assert db._to_pg_placeholders(sql).count("%s") == 1

    def test_an_escaped_quote_does_not_end_the_literal_early(self):
        sql = "SELECT ? WHERE name = 'O''Brien?'"

        assert db._to_pg_placeholders(sql) == "SELECT %s WHERE name = 'O''Brien?'"


class TestTypeMapping:
    def test_real_becomes_double_precision(self):
        """The one that would corrupt data silently.

        Postgres REAL is float4 — about seven significant digits. An epoch
        timestamp needs ten, so every created_at and expires_at would be
        rounded to the nearest few minutes: enough to expire a fresh session,
        or to un-expire a used password-reset token.
        """
        assert "DOUBLE PRECISION" in db._for_postgres("created_at REAL NOT NULL")
        assert "REAL" not in db._for_postgres("created_at REAL NOT NULL")

    def test_float4_really_would_lose_the_precision_this_guards(self):
        """Not an assumption about Postgres — arithmetic anyone can check."""
        import struct

        now = time.time()
        as_float4 = struct.unpack("f", struct.pack("f", now))[0]

        assert abs(as_float4 - now) > 1.0, "float4 cannot hold an epoch second"

    def test_the_rowid_alias_becomes_a_real_identity_column(self):
        result = db._for_postgres("id INTEGER PRIMARY KEY")

        assert "GENERATED BY DEFAULT AS IDENTITY" in result

    def test_blobs_become_bytea(self):
        assert "BYTEA" in db._for_postgres("ciphertext BLOB NOT NULL")

    def test_every_schema_statement_survives_translation(self):
        for statement in db.SCHEMA:
            translated = db._for_postgres(statement)
            assert "BLOB" not in translated
            # 'REAL' must not survive as a standalone type name.
            assert " REAL " not in translated


class TestReturningId:
    def test_only_the_table_with_a_generated_id_gets_returning(self):
        assert db._is_insert_needing_id("INSERT INTO users (email) VALUES (?)")
        # Every other table uses a natural key and has no `id` column at all,
        # so appending RETURNING id would be an error rather than a nicety.
        assert not db._is_insert_needing_id(
            "INSERT INTO sessions (token, user_id) VALUES (?, ?)"
        )
        assert not db._is_insert_needing_id("SELECT id FROM users")

    def test_an_existing_returning_clause_is_not_doubled(self):
        assert not db._is_insert_needing_id(
            "INSERT INTO users (email) VALUES (?) RETURNING id"
        )


# ------------------------------------------------------------- integration

TEST_DATABASE_URL = os.getenv("TEST_DATABASE_URL", "").strip()

# Captured at import, which is the only moment it is still visible: the autouse
# fixture in conftest deletes DATABASE_URL from the environment before any test
# runs. Reading it inside the fixture therefore always saw an empty string, and
# the safety check below silently passed — which is how these tests dropped the
# production tables a second time after the guard was added.
LIVE_DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
postgres_only = pytest.mark.skipif(
    not TEST_DATABASE_URL.startswith(("postgres://", "postgresql://")),
    reason="set TEST_DATABASE_URL to a throwaway Postgres database to run these",
)


@pytest.fixture
def pg(monkeypatch):
    """A clean schema on a throwaway database, dropped again afterwards.

    The guard is not paranoia. These tests DROP TABLE on teardown, and pointed
    at production they delete every account — silently, in a green test run.
    """
    if LIVE_DATABASE_URL and LIVE_DATABASE_URL == TEST_DATABASE_URL:
        pytest.fail(
            "TEST_DATABASE_URL is the same database as DATABASE_URL. These "
            "tests drop every table; point them at a throwaway database."
        )
    monkeypatch.setenv("DATABASE_URL", TEST_DATABASE_URL)
    _drop_everything()
    accounts.init_db()
    yield
    _drop_everything()


def _schema_tables() -> list[str]:
    """Every table the app creates, read off the schema itself.

    Hardcoding the list meant it went stale the moment a table was added: the
    LLM budget tables were not dropped between tests, so counts leaked from one
    test into the next and the failures pointed at the wrong code.
    """
    names = []
    for statement in db.SCHEMA:
        match = re.search(r"CREATE TABLE IF NOT EXISTS (\w+)", statement)
        if match:
            names.append(match.group(1))
    return names


def _drop_everything() -> None:
    with db.connect() as conn:
        for table in _schema_tables():
            conn.execute(f"DROP TABLE IF EXISTS {table} CASCADE")


