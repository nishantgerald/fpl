@postgres_only
def test_deleting_a_user_takes_their_sessions_with_them(pg):
    """The property that decided Postgres over Aurora DSQL.

    DSQL has no foreign keys, so this cascade would have to be re-implemented
    in application code — and a missed path leaves a revoked user's session
    tokens working, which is a security bug rather than untidiness.
    """
    user = accounts.register("nish@example.com", "a-decent-password")
    token = accounts.authenticate("nish@example.com", "a-decent-password")
    accounts.link_fpl(user["id"], 2670555, "Team", "Nishant")

    with db.connect() as conn:
        conn.execute("DELETE FROM users WHERE id = ?", (user["id"],))

    assert accounts.user_for_token(token) is None
    with db.connect() as conn:
        leftovers = conn.execute(
            "SELECT COUNT(*) AS n FROM sessions WHERE user_id = ?", (user["id"],)
        ).fetchone()
    assert leftovers["n"] == 0


@postgres_only
def test_timestamps_survive_the_round_trip_to_the_second(pg):
    """Guards the float4 trap from the other side: a stored expiry that drifts
    by minutes silently expires live sessions."""
    user = accounts.register("nish@example.com", "a-decent-password")
    accounts.authenticate("nish@example.com", "a-decent-password")

    with db.connect() as conn:
        row = conn.execute(
            "SELECT created_at, expires_at FROM sessions WHERE user_id = ?",
            (user["id"],),
        ).fetchone()

    assert abs(row["created_at"] - time.time()) < 60
    span = row["expires_at"] - row["created_at"]
    assert abs(span - accounts.SESSION_TTL_SECONDS) < 1


